package io.github.vishwassp01.relevanceeval.stats;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.util.HashMap;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.within;

class PairedRandomizationTestTest {

    private PairedRandomizationTest test;

    @BeforeEach
    void setUp() {
        test = new PairedRandomizationTest();
    }

    /**
     * Reasoning:
     * When baseline and candidate scores are identical for all queries, every score delta
     * (candidate - baseline) is exactly 0.0. Consequently, the observed meanDelta is 0.0.
     * In every permutation trial, multiplying 0.0 by +1 or -1 still results in 0.0, so the trial
     * mean is always 0.0. Because |0.0| >= |0.0| is true for every trial, count equals trials,
     * and pValue = (trials + 1) / (trials + 1) = 1.0.
     */
    @Test
    void identicalRunsProduceMeanDeltaZeroAndPValueNearOne() {
        Map<String, Double> baseline = Map.of(
                "running shoes", 0.85,
                "waterproof jacket", 0.70,
                "wireless headphones", 0.60
        );
        Map<String, Double> candidate = Map.of(
                "running shoes", 0.85,
                "waterproof jacket", 0.70,
                "wireless headphones", 0.60
        );

        SignificanceResult result = test.test(baseline, candidate);

        assertThat(result.sampleSize()).isEqualTo(3);
        assertThat(result.meanDelta()).isCloseTo(0.0, within(1e-9));
        assertThat(result.pValue()).isCloseTo(1.0, within(1e-9));
    }

    /**
     * Reasoning:
     * When every query shows a large and consistent improvement (e.g. candidate outperforming
     * baseline by +0.50 across 20 queries), the observed statistic is meanDelta = +0.50.
     * In the randomization test, each delta's sign is flipped with p = 0.5. The probability that
     * random sign flips produce a mean with |trialMean| >= 0.50 requires all 20 signs to be positive
     * or all 20 to be negative, which has probability 2 * (0.5)^20 ≈ 1.9e-6.
     * Out of 10,000 trials, the expected count of such extreme permutations is near 0,
     * leading to pValue = (count + 1) / (10000 + 1) < 0.05, establishing statistical significance.
     */
    @Test
    void substantialImprovementAcrossAllQueriesYieldsSmallPValue() {
        Map<String, Double> baseline = new HashMap<>();
        Map<String, Double> candidate = new HashMap<>();
        for (int i = 1; i <= 20; i++) {
            String query = "query-" + i;
            baseline.put(query, 0.30);
            candidate.put(query, 0.80); // delta = +0.50 for all 20 queries
        }

        SignificanceResult result = test.test(baseline, candidate);

        assertThat(result.sampleSize()).isEqualTo(20);
        assertThat(result.meanDelta()).isCloseTo(0.50, within(1e-9));
        assertThat(result.pValue()).isLessThan(0.05);
    }

    /**
     * Reasoning:
     * Paired randomization testing relies on pseudo-random sign assignments generated by
     * java.util.Random seeded with a specific seed. Re-running the test on the same inputs
     * with the exact same seed must produce identical sign sequences, identical trial counts,
     * and identical resulting SignificanceResult values, guaranteeing deterministic reproducibility.
     */
    @Test
    void sameSeedGivesIdenticalResultsTwice() {
        Map<String, Double> baseline = Map.of(
                "query-1", 0.55,
                "query-2", 0.72,
                "query-3", 0.40,
                "query-4", 0.90
        );
        Map<String, Double> candidate = Map.of(
                "query-1", 0.60,
                "query-2", 0.68,
                "query-3", 0.45,
                "query-4", 0.95
        );

        long seed = 12345L;
        int trials = 5000;
        SignificanceResult run1 = test.test(baseline, candidate, trials, seed);
        SignificanceResult run2 = test.test(baseline, candidate, trials, seed);

        assertThat(run1).isEqualTo(run2);
        assertThat(run1.pValue()).isEqualTo(run2.pValue());
        assertThat(run1.meanDelta()).isEqualTo(run2.meanDelta());
        assertThat(run1.sampleSize()).isEqualTo(run2.sampleSize());
        assertThat(run1.trials()).isEqualTo(run2.trials());
    }

    /**
     * Reasoning:
     * When inputs are empty or have no overlapping queries, sampleSize is 0.
     * The method must not throw exceptions (such as ArithmeticException from division by zero
     * or IndexOutOfBoundsException), and must return a safe fallback of pValue = 1.0,
     * meanDelta = 0.0, and sampleSize = 0 per the specification.
     */
    @Test
    void emptyInputDoesNotThrow() {
        SignificanceResult emptyMaps = test.test(Map.of(), Map.of());
        assertThat(emptyMaps.sampleSize()).isZero();
        assertThat(emptyMaps.meanDelta()).isEqualTo(0.0);
        assertThat(emptyMaps.pValue()).isEqualTo(1.0);

        // Disjoint sets sharing no common queries
        SignificanceResult disjointMaps = test.test(
                Map.of("query-A", 0.5),
                Map.of("query-B", 0.8)
        );
        assertThat(disjointMaps.sampleSize()).isZero();
        assertThat(disjointMaps.meanDelta()).isEqualTo(0.0);
        assertThat(disjointMaps.pValue()).isEqualTo(1.0);
    }

    /**
     * Reasoning:
     * When there is only a single shared query (sampleSize = 1), there is only one delta d.
     * The observed statistic is meanDelta = d, so |observedMean| = |d|.
     * In each trial, flipping the sign produces trial mean +d or -d, whose absolute magnitude
     * |+/-d| = |d| is always >= |observedMean| (|d|).
     * Hence every trial counts toward the threshold, yielding count = trials and
     * pValue = (trials + 1) / (trials + 1) = 1.0, without throwing errors.
     */
    @Test
    void singleQueryDoesNotThrow() {
        Map<String, Double> baseline = Map.of("single-query", 0.40);
        Map<String, Double> candidate = Map.of("single-query", 0.90);

        SignificanceResult result = test.test(baseline, candidate);

        assertThat(result.sampleSize()).isEqualTo(1);
        assertThat(result.meanDelta()).isCloseTo(0.50, within(1e-9));
        assertThat(result.pValue()).isCloseTo(1.0, within(1e-9));
    }

    /**
     * Reasoning:
     * Queries present in only one of the runs must be ignored, ensuring sampleSize and meanDelta
     * reflect only matched pairs.
     */
    @Test
    void takesOnlyQueriesPresentInBothMaps() {
        Map<String, Double> baseline = Map.of(
                "q-common-1", 0.40,
                "q-common-2", 0.60,
                "q-only-baseline", 0.90
        );
        Map<String, Double> candidate = Map.of(
                "q-common-1", 0.50, // delta = +0.10
                "q-common-2", 0.80, // delta = +0.20
                "q-only-candidate", 0.10
        );

        SignificanceResult result = test.test(baseline, candidate);

        assertThat(result.sampleSize()).isEqualTo(2);
        // Mean delta: (0.10 + 0.20) / 2 = 0.15
        assertThat(result.meanDelta()).isCloseTo(0.15, within(1e-9));
        assertThat(result.trials()).isEqualTo(PairedRandomizationTest.DEFAULT_TRIALS);
    }
}
